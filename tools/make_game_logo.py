#!/usr/bin/env python3
"""Native monochrome F/1 racing mark: launcher icon and UI resource, no dependencies."""
from pathlib import Path
import struct,zlib
ROOT=Path(__file__).resolve().parent.parent
# Slanted F wing, a second speed stripe and a separate forward-slanting 1.
POLYS=[[(0,10),(6,2),(9,0),(24,0),(21,3),(10,3),(8,4),(4,10)],
       [(6,10),(10,5),(19,5),(17,7),(12,7),(10,10)],
       [(21,10),(28,0),(34,0),(27,10)]]
def inside(x,y,poly):
    result=False
    for i,a in enumerate(poly):
        b=poly[i-1]
        if (a[1]>y)!=(b[1]>y) and x<(b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]:result=not result
    return result

def raster(w,h):return [[int(any(inside((x+.5)*34/w,(y+.5)*10/h,p) for p in POLYS)) for x in range(w)] for y in range(h)]
def png(path,pixels):
    h=len(pixels);w=len(pixels[0])
    raw=b''.join(b'\0'+bytes(0 if v else 255 for v in row) for row in pixels)
    def chunk(t,d):return struct.pack('>I',len(d))+t+d+struct.pack('>I',zlib.crc32(t+d))
    path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,8,0,0,0,0))+chunk(b'IDAT',zlib.compress(raw))+chunk(b'IEND',b''))
# SDK launcher icons use a 10x10 square; preserve the mark's wide aspect inside it.
mark=raster(10,4);png(ROOT/'icon.png',[[0]*10 for _ in range(3)]+mark+[[0]*10 for _ in range(3)])
rows=raster(34,10)
values=[sum(v<<x for x,v in enumerate(row)) for row in rows]
(ROOT/'game_logo.h').write_text('/* Generated by tools/make_game_logo.py. */\n#ifndef GP_GAME_LOGO_H\n#define GP_GAME_LOGO_H\nstatic const uint64_t gp_game_logo[10]={\n'+',\n'.join('    0x%09xULL'%n for n in values)+'\n};\n#endif\n')
# Large preview shows the exact menu pixels and launcher icon side by side.
preview=[[0]*220 for _ in range(70)]
for x0,y0,data,scale in [(4,12,rows,4),(160,12,[[0]*10 for _ in range(3)]+mark+[[0]*10 for _ in range(3)],4)]:
    for y,row in enumerate(data):
        for x,v in enumerate(row):
            for yy in range(scale):
                for xx in range(scale):preview[y0+y*scale+yy][x0+x*scale+xx]=v
png(ROOT/'assets/game_logo.png',preview)
