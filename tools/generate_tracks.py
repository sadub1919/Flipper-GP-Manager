#!/usr/bin/env python3
"""Convert real F1 GeoJSON coordinates to a compact Flipper Zero line renderer.
GeoJSON source: bacinger/f1-circuits (MIT license).
Source: https://github.com/bacinger/f1-circuits
Must NOT silently fall back to invented or schematic maps.
"""
import argparse
import json
import math
import pathlib
import sys
import urllib.request

URL='https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson'
BASE=pathlib.Path(__file__).resolve().parent.parent
TRACKS=[
 ('Melbourne','au-1953'),('Shanghai','cn-2004'),('Suzuka','jp-1962'),
 ('Miami','us-2022'),('Montreal','ca-1978'),('Monaco','mc-1929'),
 ('Barcelona','es-1991'),('Spielberg','at-1969'),('Silverstone','gb-1948'),
 ('Spa','be-1925'),('Hungaroring','hu-1986'),('Zandvoort','nl-1948'),
 ('Monza','it-1922'),('Madrid','es-2026'),('Baku','az-2016'),
 ('Sepang','my-1999'),('Singapore','sg-2008'),('Austin','us-2012'),
 ('Mexico City','mx-1962'),('Interlagos','br-1940'),('Las Vegas','us-2023'),
 ('Lusail','qa-2004'),('Yas Marina','ae-2009'),
]

def distance(p,a,b):
    dx=b[0]-a[0];dy=b[1]-a[1]
    if dx==0 and dy==0:return math.hypot(p[0]-a[0],p[1]-a[1])
    t=max(0.,min(1.,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy)))
    return math.hypot(p[0]-(a[0]+dx*t),p[1]-(a[1]+dy*t))

def simplify(points,epsilon):
    if len(points)<=2:return points
    a,b=points[0],points[-1]
    pos,d=max(((i,distance(p,a,b)) for i,p in enumerate(points[1:-1],start=1)),key=lambda a:a[1],default=(0,0))
    if d<=epsilon:return [a,b]
    return simplify(points[:pos+1],epsilon)[:-1]+simplify(points[pos:],epsilon)

def conversion(coords):
    # Equirectangular projection at circuit latitude: preserves true aspect.
    lat0=sum(x[1] for x in coords)/len(coords)
    xys=[(float(lon)*math.cos(math.radians(lat0)), -float(lat)) for lon,lat in coords]
    minx=min(x for x,y in xys);maxx=max(x for x,y in xys)
    miny=min(y for x,y in xys);maxy=max(y for x,y in xys)
    # Normalize to a fixed 80x39 screen box while preserving geographic aspect.
    dx=maxx-minx;dy=maxy-miny
    if dx<=0 or dy<=0:raise ValueError('invalid geometry')
    scale=min(76/dx,35/dy)
    offx=(80-dx*scale)/2;offy=(39-dy*scale)/2
    points=[(round((offx+(x-minx)*scale)*100/80),
             round((offy+(y-miny)*scale)*100/39)) for x,y in xys]
    # Remove identical quantized adjacent points.
    unique=[]
    for p in points:
        if not unique or unique[-1]!=p:unique.append(p)
    if len(unique)>1 and unique[0]!=unique[-1]:unique.append(unique[0])
    # A closed loop has same start and end, bad for an open polyline's RDP;
    # split around half-way to preserve real corners.
    half=len(unique)//2
    eps=0.55
    while True:
        s=simplify(unique[:half+1],eps)[:-1]+simplify(unique[half:],eps)
        if len(s)<90:break
        eps+=0.3
    if len(s)<5:raise ValueError('too few track points')
    if s[-1]!=s[0]:s[-1]=s[0]
    return s

def generate(blob):
    features={f.get('properties',{}).get('id'):f for f in blob['features']}
    result=[]
    for name,ident in TRACKS:
        if ident not in features:raise ValueError(f'Circuit not found in real GeoJSON: {name} ({ident})')
        geom=features[ident]['geometry']
        if geom['type']!='LineString':raise ValueError(f'Unsupported geometry: {name}')
        coords=geom['coordinates']
        track=conversion(coords)
        result.append((name,ident,track))
    lines=['#include "track_shapes.h"','',
      '/* REAL circuit geometry from bacinger/f1-circuits GeoJSON (MIT).',
      '   Generated by tools/generate_tracks.py using projected GPS coordinates.',
      '   Shapes are simplified to screen resolution, not hand invented.',
      '   Source: https://github.com/bacinger/f1-circuits */','',
      '#define COUNT_OF(a) (uint8_t)(sizeof(a)/sizeof((a)[0])/2)','']
    for i,(name,ident,track) in enumerate(result):
        arr=', '.join(f'{x}, {y}' for x,y in track)
        lines.append(f'/* {i+1:02d} {name} — {ident}, {len(track)} points */')
        lines.append(f'static const uint8_t t{i:02d}[] = {{{arr}}};')
    lines.append('')
    lines.append('static const GpTrackShape shapes[23] = {')
    lines.extend(f'    {{t{i:02d}, COUNT_OF(t{i:02d})}},' for i in range(23))
    lines.extend(['};',
       'const GpTrackShape* gp_track_shape(uint8_t track) {',
       '    return &shapes[track % 23];','}',''])
    return '\n'.join(lines),result

def main():
    p=argparse.ArgumentParser();p.add_argument('--input',type=pathlib.Path,help='Local GeoJSON fixture for offline tests')
    p.add_argument('--output',type=pathlib.Path,default=BASE/'track_shapes.c');a=p.parse_args()
    if a.input:
        blob=json.loads(a.input.read_text(encoding='utf-8'))
    else:
        try:
            req=urllib.request.Request(URL,headers={'User-Agent':'FlipperGPManager/0.5'})
            with urllib.request.urlopen(req,timeout=25) as response:
                blob=json.load(response)
        except Exception as e:
            print('FAILED: cannot fetch real track data from GitHub:',e,file=sys.stderr)
            print('Connect your Mac to the internet, then retry ./build_mac.sh.',file=sys.stderr)
            sys.exit(2)
    try:source,found=generate(blob)
    except Exception as e:
        print('FAILED: track verification:',e,file=sys.stderr);sys.exit(3)
    a.output.write_text(source,encoding='utf-8')
    print(f'Generated {len(found)} REAL circuit outlines -> {a.output}:')
    for name,ident,xy in found: print(f'  {name:<14} {ident:<8} {len(xy)} points')

if __name__=='__main__':main()
